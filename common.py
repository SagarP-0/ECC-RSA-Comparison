"""
common.py - shared constants and helpers.

Contents
--------
* SECURITY_LEVELS : the RSA <-> ECC equivalence table (NIST SP 800-57 Part 1).
* Secure randomness helpers (OS CSPRNG via ``secrets`` / ``os.urandom``).
  SageMath's ``random_prime`` / ``randint`` / ``ZZ.random_element`` are
  *simulation* PRNGs and are deliberately NOT used for any secret value.
* AES-256-GCM helpers (authenticated encryption; AES is never used without
  authentication anywhere in this project).
* Exceptions shared by the RSA and ECC code.
"""

import os
import secrets
from dataclasses import dataclass

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

# --------------------------------------------------------------------------
# SageMath configuration.
# With proof.arithmetic(False) Sage uses fast (BPSW) pseudoprimality tests
# instead of *proving* primality, e.g. when GF(p) is constructed for a 521-bit
# p.  The NIST primes are known primes, and RSA primes are generated by our own
# BPSW + Miller-Rabin pipeline (see rsa.py), so nothing is lost.
# --------------------------------------------------------------------------
from sage.all import proof

proof.arithmetic(False)

# --------------------------------------------------------------------------
# Security levels (approximate *classical* equivalences, NIST SP 800-57).
# These are estimates of the work factor of the best known classical attacks
# (GNFS for RSA, Pollard-rho for ECDLP), not exact guarantees.  None of the
# configurations is quantum-safe: Shor's algorithm breaks both RSA and ECC.
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class SecurityLevel:
    bits: int          # approximate classical security strength in bits
    rsa_bits: int      # RSA modulus size
    curve: str         # NIST prime curve name


SECURITY_LEVELS = {
    112: SecurityLevel(112, 2048, "P-224"),
    128: SecurityLevel(128, 3072, "P-256"),
    192: SecurityLevel(192, 7680, "P-384"),
    256: SecurityLevel(256, 15360, "P-521"),
}
DEFAULT_LEVEL = 128  # RSA-3072 vs P-256

BACKENDS = ("openssl", "sage")
DEFAULT_BACKEND = "openssl"

# --------------------------------------------------------------------------
# AES-256-GCM parameters
# --------------------------------------------------------------------------
AES_KEY_LEN = 32   # AES-256
NONCE_LEN = 12     # 96-bit nonce (the recommended GCM size)
TAG_LEN = 16       # 128-bit authentication tag


class DecryptionError(Exception):
    """Raised for *every* decryption/authentication failure.

    A single generic exception (with a generic message) is used on purpose so
    that callers - and therefore attackers - cannot distinguish *why*
    decryption failed (padding error vs. bad tag vs. malformed point ...).
    """


# --------------------------------------------------------------------------
# Secure randomness
# --------------------------------------------------------------------------


def csprng_bytes(n: int) -> bytes:
    """n random bytes from the operating-system CSPRNG (os.urandom)."""
    return os.urandom(n)


def csprng_randbelow(upper: int) -> int:
    """Uniform integer in [0, upper) from the OS CSPRNG (rejection sampling)."""
    return secrets.randbelow(upper)


# --------------------------------------------------------------------------
# AES-256-GCM (authenticated encryption)
# --------------------------------------------------------------------------


def aead_encrypt(key: bytes, plaintext: bytes, aad: bytes):
    """AES-256-GCM encrypt.  Returns (nonce, ciphertext, tag).

    A fresh random 96-bit nonce is drawn for every call.  This is safe here
    because every message uses a *fresh, single-use* key (an ephemeral-ECDH
    derived key or a random AES key), so a (key, nonce) pair can never repeat.
    """
    if len(key) != AES_KEY_LEN:
        raise ValueError("AES-256 key must be 32 bytes")
    nonce = csprng_bytes(NONCE_LEN)
    ct_and_tag = AESGCM(key).encrypt(nonce, plaintext, aad)
    return nonce, ct_and_tag[:-TAG_LEN], ct_and_tag[-TAG_LEN:]


def aead_decrypt(key: bytes, nonce: bytes, ciphertext: bytes, tag: bytes, aad: bytes) -> bytes:
    """AES-256-GCM decrypt + authenticate; raises DecryptionError on failure."""
    try:
        return AESGCM(key).decrypt(nonce, ciphertext + tag, aad)
    except InvalidTag:
        raise DecryptionError("decryption failed") from None


def lp(data: bytes) -> bytes:
    """2-byte big-endian length prefix + data (unambiguous field encoding)."""
    if len(data) > 0xFFFF:
        raise ValueError("field too long")
    return len(data).to_bytes(2, "big") + data
